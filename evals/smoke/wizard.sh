# _read VAR "prompt": one line into VAR; stops the wizard cleanly when input ends.
_read() {
  local __in
  printf '  %s%s%s ' "$BOLD" "$2" "$RESET"
  if ! IFS= read -r __in; then
    printf '\n'; warn "input ended: stopping here; nothing half-recorded"; exit 1
  fi
  printf -v "$1" '%s' "$__in"
}

# _yn VAR "question": yes or no, asked until one of them.
_yn() {
  local __a
  while :; do
    _read __a "$2 [y/n]"
    case "$__a" in [Yy]*) printf -v "$1" yes; return ;; [Nn]*) printf -v "$1" no; return ;; esac
  done
}

# _row VAR H# "n/a reason or empty": pass, fail or n/a; Enter takes n/a where hard-rows.md allows it.
_row() {
  local __a hint="p/f/n"
  [[ -n "$3" ]] && hint="p/f/n, Enter = n/a: $3"
  while :; do
    _read __a "$2 [$hint]"
    [[ -z "$__a" && -n "$3" ]] && __a=n
    case "$__a" in
      [Pp]*) printf -v "$1" pass; return ;;
      [Ff]*) printf -v "$1" fail; return ;;
      [Nn]*) printf -v "$1" n/a; return ;;
    esac
  done
}

