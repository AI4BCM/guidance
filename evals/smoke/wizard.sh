# record_client ID KEY VALUE ...: one "client" line.
record_client() {
  local id="$1"; shift
  local args=()
  while (($#)); do args+=(--arg "$1" "$2"); shift 2; done
  jq -nc --arg step "$id" --arg kit "$KIT_COMMIT" --arg at "$(now)" "${args[@]}" \
    '{kind: "client", step: $step} + ($ARGS.named | del(.step, .kit, .at)) + {kit_commit: $kit, recorded_at: $at}' \
    >> "$RESULTS"
  printf '  %s✓ recorded%s %s → %s\n' "$GREEN" "$RESET" "$id" "$RESULTS"
}

run_step() {
  local s="$1" id n client cname skill case label folder na_json files dir
  id=$(jq -r .id <<<"$s");          n=$(jq -r .n <<<"$s")
  client=$(jq -r .client <<<"$s");  cname=$(jq -r .client_name <<<"$s")
  skill=$(jq -r .skill <<<"$s");    case=$(jq -r .case <<<"$s")
  label=$(jq -r .label <<<"$s");    folder=$(jq -r .folder <<<"$s")
  na_json=$(jq -c .na <<<"$s");     files=$(jq -r '.files | join(", ")' <<<"$s")
  dir="$BASE/$folder"
  if recorded "$id"; then skip_stage; return; fi
  if [[ "$client" == chatgpt && "$CHATGPT_OFF" == 1 ]]; then skip_stage; return; fi

  stage "$cname · /$skill · case $case ($label) · run $n of 24"
  say "Folder on the laptop: ${BOLD}$folder/${RESET}"
  if [[ "$client" == chatgpt ]]; then
    step "Upload chatgpt-upload/$skill.zip if this skill is not in ChatGPT yet (Plugins > Skills > Create > Upload from your computer), in the form your first upload settled: ${CHATGPT_FORM:-see stage 2}."
    if [[ -s "$dir/request-after-name.txt" ]] && [[ -n "$(tr -d '[:space:]' < "$dir/request-after-name.txt")" ]]; then
      step "Open a new chat. Type @$skill and pick the skill from the list, then paste request-after-name.txt after it. The request, verbatim from cases.md:"
    else
      step "Open a new chat. Type @$skill, pick the skill from the list, and send the mention alone. The request, verbatim from cases.md:"
    fi
    show_file "$dir/request.txt"
    if [[ -n "$files" ]]; then step "Attach from files/: $files"; else step "Attach nothing."; fi
  else
    step "VS Code: File > Open Folder > $folder/workspace. Open Copilot Chat in Agent mode, start a new chat."
    step "Paste request.txt as it stands:"
    show_file "$dir/request.txt"
    if [[ -n "$files" ]]; then step "Attach nothing: $files already sit in the workspace."; else step "Attach nothing."; fi
  fi
  step "Then answer as the driver would (turns.txt; answer nothing else):"
  show_file "$dir/turns.txt"
  note "The case's own checks are in case.md beside it, and the seven rows in ai4bcm-smoke/hard-rows.md."

  local go
  _read go "Run it to the end, then press Enter to record (s = skip for now, asked again next time):"
  if [[ "$go" =~ ^[Ss] ]]; then warn "skipped, not recorded: $id"; return; fi

  local colleague line r v failed=() note_line
  _yn colleague "Would you hand this output to a colleague?"
  _read line "In one line, why:"
  local rows_args=()
  say "The seven hard rows (p = pass, f = fail, n = n/a):"
  for r in "${ROWS[@]}"; do
    note "$r ${ROW_TEXT[$r]}"
    _row v "$r" "$(jq -r --arg r "$r" '.[$r] // empty' <<<"$na_json")"
    rows_args+=(--arg "$r" "$v")
    [[ "$v" == fail ]] && failed+=("$r")
  done
  _read note_line "Anything else (a case check from case.md, the line that decided a fail), or Enter:"
  jq -nc --argjson s "$s" --arg colleague "$colleague" --arg line "$line" --arg note "$note_line" \
    --arg kit "$KIT_COMMIT" --arg at "$(now)" --arg failed "${failed[*]:-}" "${rows_args[@]}" \
    '{kind: "run", step: $s.id, n: $s.n, client: $s.client_name, skill: $s.skill, case: $s.case,
      label: $s.label, colleague: $colleague, colleague_line: $line,
      rows: ($ARGS.named | with_entries(select(.key | test("^H[1-7]$")))),
      rows_failed: ($failed | split(" ") | map(select(length > 0))),
      note: $note, kit_commit: $kit, recorded_at: $at}' >> "$RESULTS"
  printf '  %s✓ recorded%s %s%s%s%s\n' "$GREEN" "$RESET" "$id" "$RED" "${failed[*]:+ (failed: ${failed[*]})}" "$RESET"
  pause "Enter for the next run"
}

